-- GEO v26：自动监测（问题监控）
-- 监控问题库 / 监测任务 / 运行批次 / 监测明细
-- 既有表增量（geo_monitor_daily.data_source、geo_platform.provider_code）由
-- GeoSchemaMigrator.ensureAutoMonitorColumns 兼容执行（老库 ALTER、新库直接建齐）。

CREATE TABLE IF NOT EXISTS geo_monitor_question (
  id               BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
  question_text    VARCHAR(512) NOT NULL                COMMENT '监控问题（目标问题原文）',
  topic_id         BIGINT       NOT NULL                COMMENT '归属话题ID（核心词）',
  brand_words      VARCHAR(255) NOT NULL DEFAULT ''     COMMENT '品牌词，逗号分隔，空=用全局默认',
  competitor_words VARCHAR(255) NOT NULL DEFAULT ''     COMMENT '竞品词，逗号分隔，空=用全局默认',
  freq             VARCHAR(16)  NOT NULL DEFAULT '每日' COMMENT '监测频率：每日/每周',
  owner_user_id    BIGINT       NOT NULL DEFAULT 0      COMMENT '负责人用户ID，0=未分配',
  owner_name       VARCHAR(64)  NOT NULL DEFAULT ''     COMMENT '负责人展示名快照',
  enabled          TINYINT      NOT NULL DEFAULT 1      COMMENT '1=启用 0=停用',
  sort_order       INT          NOT NULL DEFAULT 0      COMMENT '排序',
  remark           VARCHAR(500) DEFAULT ''              COMMENT '备注',
  create_by        VARCHAR(50)  DEFAULT ''              COMMENT '创建者',
  create_time      DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_by        VARCHAR(50)  DEFAULT ''              COMMENT '更新者',
  update_time      DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  is_active        TINYINT      NOT NULL DEFAULT 1      COMMENT '是否有效 1=有效 0=已删除',
  PRIMARY KEY (id),
  UNIQUE KEY uk_question (question_text),
  KEY idx_topic (topic_id),
  KEY idx_enabled_freq (enabled, freq)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='GEO自动监测-监控问题库';

CREATE TABLE IF NOT EXISTS geo_monitor_task (
  id               BIGINT        NOT NULL AUTO_INCREMENT COMMENT '主键',
  task_name        VARCHAR(128)  NOT NULL                COMMENT '任务名',
  scope_type       VARCHAR(16)   NOT NULL DEFAULT 'TOPIC' COMMENT '圈选方式：TOPIC=按话题 / QUESTION=按问题',
  scope_ids        VARCHAR(2048) NOT NULL DEFAULT ''     COMMENT '圈选ID列表，逗号分隔',
  platforms        VARCHAR(255)  NOT NULL                COMMENT '监测平台名列表，逗号分隔（geo_platform.platform_name）',
  freq             VARCHAR(16)   NOT NULL DEFAULT '每日' COMMENT '每日/每周',
  run_time         TIME          NOT NULL DEFAULT '08:30:00' COMMENT '每日运行时刻',
  week_day         TINYINT       DEFAULT NULL            COMMENT '每周模式：1=周一 … 7=周日',
  overwrite_manual TINYINT       NOT NULL DEFAULT 0      COMMENT '同日同题同平台有人工记录时是否覆盖 0=人工优先',
  notify_enabled   TINYINT       NOT NULL DEFAULT 1      COMMENT '变化提醒开关（P2 生效）',
  enabled          TINYINT       NOT NULL DEFAULT 1      COMMENT '1=启用 0=停用',
  last_run_id      BIGINT        DEFAULT NULL            COMMENT '最近一次运行批次ID',
  next_run_time    DATETIME      DEFAULT NULL            COMMENT '下次运行时间',
  sort_order       INT           NOT NULL DEFAULT 0      COMMENT '排序',
  remark           VARCHAR(500)  DEFAULT ''              COMMENT '备注',
  create_by        VARCHAR(50)   DEFAULT ''              COMMENT '创建者',
  create_time      DATETIME      DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_by        VARCHAR(50)   DEFAULT ''              COMMENT '更新者',
  update_time      DATETIME      DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  is_active        TINYINT       NOT NULL DEFAULT 1      COMMENT '是否有效 1=有效 0=已删除',
  PRIMARY KEY (id),
  KEY idx_enabled_next (enabled, next_run_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='GEO自动监测-任务配置';

CREATE TABLE IF NOT EXISTS geo_monitor_run (
  id            BIGINT        NOT NULL AUTO_INCREMENT COMMENT '主键',
  task_id       BIGINT        NOT NULL                COMMENT '任务ID',
  task_name     VARCHAR(128)  NOT NULL DEFAULT ''     COMMENT '任务名快照',
  run_date      DATE          NOT NULL                COMMENT '监测归属日期（回写日监测的inspect_date）',
  trigger_type  VARCHAR(16)   NOT NULL DEFAULT 'SCHEDULED' COMMENT 'SCHEDULED/MANUAL',
  status        VARCHAR(16)   NOT NULL DEFAULT 'RUNNING' COMMENT 'RUNNING/SUCCESS/PARTIAL/FAILED',
  total_count   INT           NOT NULL DEFAULT 0      COMMENT '问题×平台总数',
  done_count    INT           NOT NULL DEFAULT 0      COMMENT '已处理数',
  success_count INT           NOT NULL DEFAULT 0      COMMENT '成功数（含SKIPPED_MANUAL）',
  failed_count  INT           NOT NULL DEFAULT 0      COMMENT '失败数（调用失败/判定失败）',
  start_time    DATETIME      NOT NULL                COMMENT '开始时间',
  end_time      DATETIME      DEFAULT NULL            COMMENT '结束时间',
  error_msg     VARCHAR(1000) DEFAULT ''              COMMENT '批次级错误摘要',
  create_by     VARCHAR(50)   DEFAULT ''              COMMENT '创建者',
  create_time   DATETIME      DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_by     VARCHAR(50)   DEFAULT ''              COMMENT '更新者',
  update_time   DATETIME      DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  is_active     TINYINT       NOT NULL DEFAULT 1      COMMENT '是否有效 1=有效 0=已删除',
  PRIMARY KEY (id),
  KEY idx_task_date (task_id, run_date),
  KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='GEO自动监测-运行批次';

CREATE TABLE IF NOT EXISTS geo_monitor_result (
  id               BIGINT        NOT NULL AUTO_INCREMENT COMMENT '主键',
  run_id           BIGINT        NOT NULL                COMMENT '批次ID',
  question_id      BIGINT        NOT NULL                COMMENT '问题ID',
  question_text    VARCHAR(512)  NOT NULL                COMMENT '问题快照',
  topic_id         BIGINT        NOT NULL                COMMENT '话题快照',
  platform         VARCHAR(32)   NOT NULL                COMMENT '平台名，同geo_platform.platform_name',
  channel          VARCHAR(16)   NOT NULL DEFAULT 'API'  COMMENT '通道：API/BROWSER',
  answer_model     VARCHAR(64)   NOT NULL DEFAULT ''     COMMENT '实际调用的模型名',
  answer_text      MEDIUMTEXT                            COMMENT 'AI回答原文（留档溯源）',
  mentioned        TINYINT       NOT NULL DEFAULT 0      COMMENT '是否提及 1=是 0=否',
  rank_no          INT           DEFAULT NULL            COMMENT '品牌在推荐列表中的位次，未出现为空',
  recommend_status VARCHAR(32)   NOT NULL DEFAULT ''     COMMENT '未出现/出现且推荐/出现未推荐',
  sentiment        VARCHAR(8)    NOT NULL DEFAULT ''     COMMENT '正面/中性/负面',
  mention_position INT           DEFAULT NULL            COMMENT '品牌首次出现于回答第几段',
  negative_content VARCHAR(500)  DEFAULT ''              COMMENT '负面/错误内容',
  competitors      VARCHAR(500)  DEFAULT ''              COMMENT '出现的竞品，逗号分隔',
  citations        JSON                                   COMMENT '引用来源 [{title,site,context}]',
  judge_raw        JSON                                   COMMENT '裁判模型原始输出（复核用）',
  status           VARCHAR(16)   NOT NULL DEFAULT 'SUCCESS' COMMENT 'SUCCESS/SKIPPED_MANUAL/JUDGE_FAILED/CALL_FAILED',
  error_msg        VARCHAR(500)  DEFAULT ''              COMMENT '失败原因',
  latency_ms       INT           DEFAULT NULL            COMMENT '单次耗时（毫秒）',
  daily_id         BIGINT        DEFAULT NULL            COMMENT '回写 geo_monitor_daily 的行ID',
  create_by        VARCHAR(50)   DEFAULT ''              COMMENT '创建者',
  create_time      DATETIME      DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_by        VARCHAR(50)   DEFAULT ''              COMMENT '更新者',
  update_time      DATETIME      DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  is_active        TINYINT       NOT NULL DEFAULT 1      COMMENT '是否有效 1=有效 0=已删除',
  PRIMARY KEY (id),
  UNIQUE KEY uk_run_q_p (run_id, question_id, platform),
  KEY idx_q_time (question_id, create_time),
  KEY idx_platform_time (platform, create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='GEO自动监测-监测明细';
